def lookup(technique_id: str) -> dict[str, Any]:
    """Guidance for a technique, or an honest fallback. Never invents details."""
    base = TECHNIQUES.get(technique_id) or TECHNIQUES.get(technique_id.split(".")[0])
    url = "https://attack.mitre.org/techniques/" + technique_id.replace(".", "/") + "/"
    if base:
        return {**base, "id": technique_id, "url": url, "curated": True}
    return {
        "id": technique_id,
        "name": technique_id,
        "tactics": [],
        "why": "No curated guidance for this technique yet.",
        "signal": "See the MITRE ATT&CK page for observable behaviours.",
        "fp": "",
        "telemetry": "unknown",
        "url": url,
        "curated": False,
    }


def primary_tactic(technique_id: str) -> str | None:
    tactics = lookup(technique_id)["tactics"]
    return tactics[0] if tactics else None
