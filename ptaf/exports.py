"""Shareable outputs: README coverage badge and MITRE ATT&CK Navigator layer.

The Navigator layer is deliberately three-state, so it cannot overstate
coverage:

* green   verified   - a canary proved the rule fires on this host
* yellow  unverified - a rule claims the technique but no canary tests it
* red     failing    - a canary ran and no rule fired (a proven gap)
"""

from __future__ import annotations

from typing import Any

from .sigma_lite import Rule
from .validation import SelfTestReport

GREEN, YELLOW, RED = "#2d6a4f", "#d4a017", "#c53030"


def badge(report: SelfTestReport) -> dict[str, Any]:
    """shields.io 'endpoint' JSON: https://shields.io/badges/endpoint-badge."""
    cov = report.coverage
    if cov is None:
        return {
            "schemaVersion": 1,
            "label": "verified detection coverage",
            "message": "n/a",
            "color": "lightgrey",
        }
    color = "brightgreen" if cov >= 90 else "yellow" if cov >= 60 else "red"
    return {
        "schemaVersion": 1,
        "label": "verified detection coverage",
        "message": f"{cov:g}%",
        "color": color,
    }


def navigator_layer(report: SelfTestReport, rules: list[Rule]) -> dict[str, Any]:
    techniques: dict[str, dict[str, Any]] = {}
    for rule in rules:
        for tid in rule.technique_ids:
            techniques.setdefault(
                tid,
                {
                    "techniqueID": tid,
                    "score": 50,
                    "color": YELLOW,
                    "comment": f"Unverified: rule '{rule.title}' maps here; no canary tests it.",
                },
            )
    for res in report.results:
        if res.status == "detected":
            techniques[res.technique_id] = {
                "techniqueID": res.technique_id,
                "score": 100,
                "color": GREEN,
                "comment": f"Verified on {report.host['hostname']}: {', '.join(res.rules_fired)}",
            }
        elif res.status == "missed":
            techniques[res.technique_id] = {
                "techniqueID": res.technique_id,
                "score": 0,
                "color": RED,
                "comment": f"GAP on {report.host['hostname']}: canary ran, no rule fired.",
            }
    return {
        "name": f"PTAF verified coverage - {report.host['hostname']}",
        "versions": {"attack": "16", "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": "Generated by PTAF Sentinel. Green=verified, yellow=unverified, red=gap.",
        "techniques": sorted(techniques.values(), key=lambda t: t["techniqueID"]),
        "legendItems": [
            {"label": "Verified (canary detected)", "color": GREEN},
            {"label": "Unverified (rule exists, untested)", "color": YELLOW},
            {"label": "Gap (canary ran, nothing fired)", "color": RED},
        ],
    }
